"""The motor/pellet board contract: the DeviceInterface subset the app calls."""

from __future__ import annotations

import typing
from typing import Protocol, Tuple, Union, runtime_checkable

from reachaq.core import Offset3DTuple

from .device_interface import AnalogOutputs, DigitalOutputs, Motor, Target


@runtime_checkable
class MotorPelletBackend(Protocol):
    """What CanDevice and DeviceConnection call on their device interface.

    `CanDevice._make_device_interface` is the one selection point: it returns
    `CanInterface` for a real transport and `EmulationInterface` for
    `AUTOTRAINER_CAN_TRANSPORT=emulation` or a missing driver. `DeviceInterface`
    stays the base class; this lists only what the app relies on.

    Threads: `open`, `close`, `can_read` and `read` run on DeviceConnection's
    reader thread; every command runs on CanDevice's command thread.

    Commands return True once they are handed to the bus, False when the
    interface is closed or the write failed. They do not wait for the board.
    A command the board must acknowledge allocates a new uuid: CanDevice reads
    `uuid()` before and after the call, and an advance means "wait for
    `Acknowledge(uuid=uuid())`", within the command's ack timeout (3 s by
    default, 0.25 s for a STIM pulse). No advance means the command completes
    at once (`request_version` does this; its answer is a Version message).
    An Acknowledge with a negative `error` is the board refusing the command.

    `read` returns the decoded messages (device_interface data classes) that
    arrived since the last call. `pellet_status_perf_c` is the perf_counter
    time of the last pellet status, in seconds; CanDevice's watchdog ages it.

    `pulse_digital_output` raises ValueError for a line other than the board's
    STIM2/STIM3 or a duration outside 100 us..5 s, before anything is sent.
    `request_capabilities` is optional (HardwareModel looks it up with getattr),
    so it is not part of the contract.
    """

    def uuid(self) -> int: ...

    @property
    def is_open(self) -> bool: ...

    @property
    def pellet_status_perf_c(self) -> float: ...

    def open(self) -> bool: ...

    def close(self): ...

    def can_read(self) -> bool: ...

    def read(self, max_count: int = 1, *, collect_ms: int = 0) -> typing.Any: ...

    def request_version(self) -> bool: ...

    def board_reboot(self, target: Target): ...

    def set_motor_configuration(self, motor: Motor, config, _write_to_remote: bool = True) -> bool: ...

    def request_motor_config(self, motor: Motor) -> bool: ...

    def set_motor_x(self, position, *, relative: bool = False) -> bool: ...

    def set_motor_y(self, position, *, relative: bool = False) -> bool: ...

    def set_motor_z(self, position, *, relative: bool = False) -> bool: ...

    def move_motor_x(self, position: float, save_as_fixed: bool = False, *, relative: bool = False) -> bool: ...

    def move_motor_y(self, position: float, save_as_fixed: bool = False, *, relative: bool = False) -> bool: ...

    def move_motor_z(self, position: float, save_as_fixed: bool = False, *, relative: bool = False) -> bool: ...

    def set_motors_drift(self, drifts: Offset3DTuple): ...

    def set_auto_correct_motor_drift(self, value): ...

    def move_servo_motor(self, motor: Motor, position: Union[float, Tuple[float, float]]): ...

    def retrieve_pellet(self) -> bool: ...

    def scoop_pellet(self) -> bool: ...

    def release_pellet(self) -> bool: ...

    def cover_pellet(self) -> bool: ...

    def fixed_position(self) -> bool: ...

    def stepper_home(self, motor: Motor): ...

    def servo_attach(self, motor: Motor): ...

    def servo_detach(self, motor: Motor): ...

    def delay(self, delay) -> bool: ...

    def emit_tone(self, frequency: int, duration_ms: int) -> bool: ...

    def set_digital_output(self, gpio: DigitalOutputs, state: bool) -> bool: ...

    def pulse_digital_output(self, gpio: DigitalOutputs, duration_us: int) -> bool: ...

    def set_analog_output(self, channel: AnalogOutputs, millivolts: int) -> bool: ...

    def set_color_led(self, red_percent: int, green_percent: int, blue_percent: int) -> bool: ...
